package com.composables.googlefonts.gradle

import org.gradle.api.DefaultTask
import org.gradle.api.file.ConfigurableFileCollection
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.provider.ListProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.*
import org.gradle.work.DisableCachingByDefault
import java.io.File

@DisableCachingByDefault(because = "Resolves and maintains a source-controlled font lockfile; downloads have a separate checksum cache")
abstract class GenerateGoogleFonts : DefaultTask() {
    @get:Input abstract val families: ListProperty<String>
    @get:Input abstract val packageName: Property<String>
    @get:Input abstract val multiplatform: Property<Boolean>
    @get:Input abstract val resourcePackage: Property<String>
    @get:Input abstract val resourceClass: Property<String>
    @get:Input abstract val offline: Property<Boolean>
    @get:InputFiles @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val existingResources: ConfigurableFileCollection
    @get:OutputFile abstract val lockFile: RegularFileProperty
    @get:Internal abstract val cacheDirectory: DirectoryProperty
    @get:OutputDirectory abstract val kotlinDirectory: DirectoryProperty
    @get:OutputDirectory abstract val wasmDirectory: DirectoryProperty
    @get:OutputDirectory abstract val resourceDirectory: DirectoryProperty
    @get:OutputDirectory abstract val assetsDirectory: DirectoryProperty

    @TaskAction
    fun generate() {
        val selected = validateFamilies(families.get())
        val pkg = packageName.get()
        require(pkg.split('.').all { it.matches(Regex("[a-zA-Z_][a-zA-Z0-9_]*")) && it !in kotlinKeywords }) {
            "Choose a valid Kotlin package for googleFonts.packageName."
        }
        val cmp = multiplatform.get()
        val resources = resourceDirectory.get().asFile
        val assets = assetsDirectory.get().asFile
        val sources = kotlinDirectory.get().asFile
        val wasm = wasmDirectory.get().asFile
        listOf(resources, assets, sources, wasm).forEach { it.deleteRecursively(); it.mkdirs() }
        if (cmp) existingResources.files.forEach { directory ->
            if (directory.exists()) directory.copyRecursively(resources, overwrite = false)
        }
        val licenses = if (cmp) resources.resolve("files/googleFonts/licenses") else assets.resolve("googleFonts/licenses")
        FontDownloader(cacheDirectory.get().asFile, offline.get(), progress = { logger.lifecycle(it) })
            .bundle(selected, lockFile.get().asFile, resources.resolve("font"), licenses)
        writeSource(sources, pkg, "GoogleFonts.kt", generateAccessors(selected, pkg, resourcePackage.get(), resourceClass.get(), cmp))
        if (cmp) writeSource(wasm, pkg, "GoogleFontsPreload.kt", generatePreload(selected, pkg, resourcePackage.get(), resourceClass.get()))
    }
}

private fun writeSource(root: File, pkg: String, name: String, text: String) {
    root.resolve("${pkg.replace('.', '/')}/$name").apply { parentFile.mkdirs(); writeText(text) }
}

internal fun generateAccessors(families: List<BundledFamily>, pkg: String, resPackage: String, resClass: String, cmp: Boolean): String = buildString {
    appendLine("// Generated by Compose Google Fonts. Do not edit.")
    appendLine("package $pkg")
    appendLine()
    appendLine("import androidx.compose.runtime.Composable")
    appendLine("import androidx.compose.runtime.remember")
    appendLine("import androidx.compose.ui.text.font.FontFamily")
    appendLine("import androidx.compose.ui.text.font.FontStyle")
    appendLine("import androidx.compose.ui.text.font.FontWeight")
    appendLine("import ${if (cmp) "org.jetbrains.compose.resources" else "androidx.compose.ui.text.font"}.Font")
    if (cmp) {
        appendLine("import $resPackage.$resClass")
        families.flatMap { it.faces }.forEach { appendLine("import $resPackage.${it.resourceName}") }
    } else appendLine("import $resPackage.R")
    appendLine()
    appendLine("public object GoogleFonts {")
    families.forEach { family ->
        appendLine("    public val ${family.accessor}: FontFamily")
        appendLine("        @Composable")
        appendLine("        get() {")
        family.faces.forEachIndexed { i, face ->
            val resource = if (cmp) "$resClass.font.${face.resourceName}" else "R.font.${face.resourceName}"
            appendLine("            val font$i = Font($resource, weight = FontWeight(${face.weight}), style = FontStyle.${if (face.italic) "Italic" else "Normal"})")
        }
        val args = family.faces.indices.joinToString(", ") { "font$it" }
        appendLine("            return remember($args) { FontFamily($args) }")
        appendLine("        }")
    }
    appendLine("}")
}

internal fun generatePreload(families: List<BundledFamily>, pkg: String, resPackage: String, resClass: String): String = buildString {
    appendLine("// Generated by Compose Google Fonts. Do not edit.")
    appendLine("package $pkg")
    appendLine()
    appendLine("import androidx.compose.runtime.Composable")
    appendLine("import androidx.compose.ui.text.font.FontStyle")
    appendLine("import androidx.compose.ui.text.font.FontWeight")
    appendLine("import org.jetbrains.compose.resources.ExperimentalResourceApi")
    appendLine("import org.jetbrains.compose.resources.preloadFont")
    appendLine("import $resPackage.$resClass")
    val faces = families.flatMap { it.faces }
    faces.forEach { appendLine("import $resPackage.${it.resourceName}") }
    appendLine()
    appendLine("/** Returns true when every bundled font is ready. Call from your Wasm startup composition. */")
    appendLine("@OptIn(ExperimentalResourceApi::class)")
    appendLine("@Composable")
    appendLine("public fun GoogleFonts.preload(): Boolean {")
    faces.forEachIndexed { i, face ->
        appendLine("    val ready$i = preloadFont($resClass.font.${face.resourceName}, weight = FontWeight(${face.weight}), style = FontStyle.${if (face.italic) "Italic" else "Normal"}).value != null")
    }
    appendLine("    return ${faces.indices.joinToString(" && ") { "ready$it" }.ifEmpty { "true" }}")
    appendLine("}")
}

private val kotlinKeywords = setOf("as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface", "is", "null", "object", "package", "return", "super", "this", "throw", "true", "try", "typealias", "typeof", "val", "var", "when", "while")
